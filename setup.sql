-- รันทั้งหมดใน Supabase Dashboard > SQL Editor
-- 1) ตารางรูปภาพ
create table if not exists public.resort_photos (
  id bigint generated by default as identity primary key,
  section text not null check (section in ('room','gallery')),
  room_number integer null check (room_number between 1 and 3),
  storage_path text not null unique,
  original_name text,
  created_at timestamptz not null default now(),
  constraint room_number_matches_section check (
    (section = 'room' and room_number is not null) or
    (section = 'gallery' and room_number is null)
  )
);

-- 2) รายชื่อบัญชีที่เป็นผู้ดูแลเท่านั้น
create table if not exists public.resort_admins (
  user_id uuid primary key references auth.users(id) on delete cascade
);

alter table public.resort_photos enable row level security;
alter table public.resort_admins enable row level security;

-- ฟังก์ชันตรวจสอบสิทธิ์ผู้ดูแล
create or replace function public.is_resort_admin()
returns boolean language sql stable security definer set search_path = public
as $$ select exists (select 1 from public.resort_admins where user_id = auth.uid()); $$;

-- ลูกค้าทุกคนอ่านรายการรูปได้ แต่เฉพาะผู้ดูแลเพิ่ม/ลบได้
 drop policy if exists "Public can read resort photos" on public.resort_photos;
create policy "Public can read resort photos" on public.resort_photos for select using (true);
drop policy if exists "Admins can insert resort photos" on public.resort_photos;
create policy "Admins can insert resort photos" on public.resort_photos for insert to authenticated with check (public.is_resort_admin());
drop policy if exists "Admins can delete resort photos" on public.resort_photos;
create policy "Admins can delete resort photos" on public.resort_photos for delete to authenticated using (public.is_resort_admin());

-- สร้าง public bucket สำหรับรูปภาพ
insert into storage.buckets (id,name,public,file_size_limit,allowed_mime_types)
values ('resort-photos','resort-photos',true,10485760,array['image/jpeg','image/png','image/webp','image/gif'])
on conflict (id) do update set public=true, file_size_limit=10485760, allowed_mime_types=array['image/jpeg','image/png','image/webp','image/gif'];

drop policy if exists "Public can view resort images" on storage.objects;
create policy "Public can view resort images" on storage.objects for select using (bucket_id='resort-photos');
drop policy if exists "Admins can upload resort images" on storage.objects;
create policy "Admins can upload resort images" on storage.objects for insert to authenticated with check (bucket_id='resort-photos' and public.is_resort_admin());
drop policy if exists "Admins can delete resort images" on storage.objects;
create policy "Admins can delete resort images" on storage.objects for delete to authenticated using (bucket_id='resort-photos' and public.is_resort_admin());

